SELECT 
    c.CUS_ID,
    c.CUS_FNAME,
    COUNT(*) AS PURCHASE_COUNT,
    AVG(ii.PRICE) AS AVG_PRICE,
    MAX(ii.PRICE) AS MAX_PRICE
FROM CUSTOMER c
JOIN INVOICE i ON c.CUS_ID = i.CUS_ID
JOIN INVOICE_ITEM ii ON i.INV_ID = ii.INV_ID
WHERE ii.PRICE > 50
GROUP BY c.CUS_ID, c.CUS_FNAME
ORDER BY MAX(ii.PRICE) DESC
LIMIT 3;

