CREATE PROCEDURE GetCustomerInvoices(IN customer_id INT)
BEGIN
    SELECT 
        c.CUS_FNAME,
        c.CUS_LNAME,
        i.INV_ID,
        i.INV_DATE,
        SUM(ii.QUANTITY * ii.PRICE) AS TOTAL
    FROM CUSTOMER c
    JOIN INVOICE i ON c.CUS_ID = i.CUS_ID
    JOIN INVOICE_ITEM ii ON i.INV_ID = ii.INV_ID
    WHERE c.CUS_ID = customer_id
    GROUP BY i.INV_ID;
END;

